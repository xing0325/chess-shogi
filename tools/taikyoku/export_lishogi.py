#!/usr/bin/env python3
"""把大局选将的棋子数据导出给 lishogi 生态:
  - scalashogi: src/main/scala/variant/TaikyokuData.scala(每种棋子一行紧凑字符串,运行时解析,避开 JVM 64KB 方法上限)
  - shogiops:   src/variant/taikyoku-data.ts(同一份编码字符串 + 同一套解析)

用法: python3 export_lishogi.py <scalashogi 仓库> <shogiops 仓库>
数据源: ../../shared/src/taikyoku/pieces.data.ts(由 build_data.py 从维基百科 rev 1378938316 生成)

行格式: id|kanji|en|rank|base|inPool|promotesTo|betza|rules
规则以 ';' 分隔:
  s:dx:dy:max:mode:hops   滑行(max 为空=不限;mode 为空/m/c;hops 为可越过的棋子数)
  l:dx:dy:mode            跳到固定格
  j:dx:dy:jump:max:jmode  跳到第 jump 格后可继续滑行
  h:dx:dy:tx,ty/tx,ty     钩行(沿 d 滑行,途中可转向 turn 之一)
  L                       狮子(两次王步)
  I                       居喰(吃掉相邻棋子后留在原地)
  r:dx:dy                 跳越吃子
向量以先手视角为准:dx>0 = 先手的右侧,dy>0 = 向前。
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "shared", "src", "taikyoku", "pieces.data.ts")


def load_kinds():
    s = open(SRC, encoding="utf-8").read()
    m = re.search(r"=\s*(\[.*\])\s*(as const)?;?\s*$", s, re.S)
    return json.loads(m.group(1))


def enc_rule(r):
    t = r["t"]
    n = lambda v: "" if v is None else str(v)
    if t == "slide":
        return f"s:{r['d'][0]}:{r['d'][1]}:{n(r.get('max'))}:{r.get('mode', '')}:{r.get('hops', 0)}"
    if t == "leap":
        return f"l:{r['d'][0]}:{r['d'][1]}:{r.get('mode', '')}"
    if t == "jumpslide":
        return f"j:{r['d'][0]}:{r['d'][1]}:{r['jump']}:{n(r.get('max'))}:{r.get('jmode', '')}"
    if t == "hook":
        return f"h:{r['d'][0]}:{r['d'][1]}:" + "/".join(f"{a},{b}" for a, b in r["turn"])
    if t == "lion":
        return "L"
    if t == "igui":
        return "I"
    if t == "rangecap":
        return f"r:{r['d'][0]}:{r['d'][1]}"
    raise ValueError(t)


def enc_kind(k):
    fields = [k["id"], k["kanji"], k["en"], str(k["rank"]), "1" if k["base"] else "0",
              "1" if k["inPool"] else "0", k["promotesTo"] or "", k["betza"],
              ";".join(enc_rule(r) for r in k["rules"])]
    for f in fields:
        assert "|" not in f and '"' not in f and "\\" not in f, (k["id"], f)
    return "|".join(fields)


def main():
    scalashogi, shogiops = sys.argv[1], sys.argv[2]
    kinds = load_kinds()
    lines = [enc_kind(k) for k in kinds]
    header = ("Generated by chess-shogi tools/taikyoku/export_lishogi.py - do not edit.\n"
              "Source: https://en.wikipedia.org/wiki/Taikyoku_shogi (rev 1378938316, CC BY-SA 4.0);\n"
              "each Betza string was compiled to rules and cross-checked against the article's move diagrams.")
    scala = ["package shogi", "package variant", "", "/*", *(" * " + h for h in header.split("\n")), " */",
             "private[shogi] object TaikyokuData {", "", "  // id|kanji|en|rank|base|inPool|promotesTo|betza|rules",
             "  val lines: List[String] = List("]
    scala += [f'    {json.dumps(l, ensure_ascii=False)},' for l in lines]
    scala += ["  )", "}", ""]
    out = os.path.join(scalashogi, "src", "main", "scala", "variant", "TaikyokuData.scala")
    open(out, "w", encoding="utf-8").write("\n".join(scala))
    ts = ["/*", *(" * " + h for h in header.split("\n")), " */", "",
          "// id|kanji|en|rank|base|inPool|promotesTo|betza|rules", "export const TAIKYOKU_LINES: readonly string[] = ["]
    ts += [f"  {json.dumps(l, ensure_ascii=False)}," for l in lines]
    ts += ["];", ""]
    out2 = os.path.join(shogiops, "src", "variant", "taikyoku-data.ts")
    os.makedirs(os.path.dirname(out2), exist_ok=True)
    open(out2, "w", encoding="utf-8").write("\n".join(ts))
    print(f"{len(lines)} kinds -> {out}, {out2}")


if __name__ == "__main__":
    main()
